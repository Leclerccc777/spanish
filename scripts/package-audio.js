// Validate the complete corpus before replacing any generated audio files.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),source=process.argv[2];
if(!source)throw new Error('Usage: node scripts/package-audio.js <generated MP3 directory>');
const texts=require('./audio-texts'),manifest={},files=new Map();
const pageFiles={
 'index.js':"Page({back(){wx.navigateBack();}});\n",
 'index.json':JSON.stringify({navigationBarTitleText:'西语语音包'})+'\n',
 'index.wxml':'<view class="page"><view class="title">语音包已准备好</view><view class="body">返回课程，点击“听发音”即可使用。内置音频为西班牙西语合成音，不自动评价发音。</view><button class="primary" bindtap="back">返回课程</button></view>\n'
};
const pageBytes=Object.values(pageFiles).reduce((n,s)=>n+Buffer.byteLength(s),0);
let pack=1,size=pageBytes,total=0;const packs=new Set();
for(const text of texts){
 const key=crypto.createHash('sha256').update(text).digest('hex').slice(0,16),name=key+'.mp3',bytes=fs.readFileSync(path.join(source,name));
 if(bytes.length<500||bytes.toString('ascii',0,3)!=='ID3')throw Error('Invalid audio: '+name);
 if(size+bytes.length>1500000){pack++;size=pageBytes;}
 const folder=`voice${pack}`,file=`${folder}/${name}`;
 if(files.has(file))throw Error('Duplicate audio hash: '+name);
 files.set(file,bytes);manifest[text]=file;packs.add(folder);size+=bytes.length;total+=bytes.length;
}
const appPath=path.join(root,'miniprogram/app.json'),app=JSON.parse(fs.readFileSync(appPath));
const oldManifest=require('../miniprogram/data/audio-manifest');
const oldPacks=(app.subPackages||[]).filter(p=>/^voice\d+$/.test(p.root));
app.subPackages=[...(app.subPackages||[]).filter(p=>!/^voice\d+$/.test(p.root)),...[...packs].map(name=>({name,root:name,pages:['index']}))];
const manifestSource='// Generated by scripts/package-audio.js; exact Spanish text → bundled MP3.\nmodule.exports = '+JSON.stringify(manifest,null,2)+';\n';
function folderBytes(dir){return fs.readdirSync(dir,{withFileTypes:true}).reduce((n,e)=>n+(e.isDirectory()?folderBytes(path.join(dir,e.name)):fs.statSync(path.join(dir,e.name)).size),0);}
const base=path.join(root,'miniprogram'),manifestPath=path.join(base,'data/audio-manifest.js'),appSource=JSON.stringify(app,null,2)+'\n';
const owned=new Set(Object.values(oldManifest));
for(const folder of new Set([...oldPacks.map(p=>p.root),...packs])){
 const dir=path.join(base,folder);
 if(!fs.existsSync(dir))continue;
 for(const name of fs.readdirSync(dir))if(!owned.has(folder+'/'+name)&&!Object.hasOwn(pageFiles,name))throw Error('Unmanaged file in audio package; no files changed: '+folder+'/'+name);
}
const otherPackages=app.subPackages.filter(p=>!/^voice\d+$/.test(p.root));
const mainBytes=folderBytes(base)-[...oldPacks,...otherPackages].reduce((n,p)=>n+folderBytes(path.join(base,p.root)),0)
 -fs.statSync(manifestPath).size-fs.statSync(appPath).size+Buffer.byteLength(manifestSource)+Buffer.byteLength(appSource);
if(mainBytes>=2*1024*1024)throw Error('Main package exceeds 2 MiB: '+mainBytes);
if(mainBytes+total+packs.size*pageBytes+otherPackages.reduce((n,p)=>n+folderBytes(path.join(base,p.root)),0)>=20*1024*1024)throw Error('Complete audio exceeds total 20 MiB; no files changed.');
// Delete only files owned by the previous generated manifest, never whole directories.
for(const file of Object.values(oldManifest))if(!files.has(file))fs.rmSync(path.join(base,file));
for(const [file,bytes] of files){const dest=path.join(base,file);fs.mkdirSync(path.dirname(dest),{recursive:true});fs.writeFileSync(dest,bytes);}
for(const folder of packs)for(const [name,content] of Object.entries(pageFiles))fs.writeFileSync(path.join(base,folder,name),content);
for(const p of oldPacks)if(!packs.has(p.root)){
 for(const name of Object.keys(pageFiles))fs.rmSync(path.join(base,p.root,name));
 if(!fs.readdirSync(path.join(base,p.root)).length)fs.rmdirSync(path.join(base,p.root));
}
fs.writeFileSync(manifestPath,manifestSource);fs.writeFileSync(appPath,appSource);
console.log(`${texts.length} audio clips, ${total} bytes, ${packs.size} native subpackages; main ${mainBytes} bytes.`);
