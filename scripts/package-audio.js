// Run after generate-audio.py. Keep each native audio subpackage below 1.5 MiB.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),source=process.argv[2];
if(!source)throw new Error('Usage: node scripts/package-audio.js <generated MP3 directory>');
const texts=require('./audio-texts'),manifest={};let pack=1,size=0,total=0;const packs=new Set();
for(const text of texts){
 const key=crypto.createHash('sha256').update(text).digest('hex').slice(0,16),name=key+'.mp3',bytes=fs.readFileSync(path.join(source,name));
 if(size+bytes.length>1500000){pack++;size=0;}
 const folder=`voice${pack}`,dest=path.join(root,'miniprogram',folder);fs.mkdirSync(dest,{recursive:true});
 fs.writeFileSync(path.join(dest,name),bytes);manifest[text]=`${folder}/${name}`;packs.add(folder);size+=bytes.length;total+=bytes.length;
}
for(const folder of packs){
 const dest=path.join(root,'miniprogram',folder);
 fs.writeFileSync(path.join(dest,'index.js'),"Page({back(){wx.navigateBack();}});\n");
 fs.writeFileSync(path.join(dest,'index.json'),JSON.stringify({navigationBarTitleText:'西语语音包'})+'\n');
 fs.writeFileSync(path.join(dest,'index.wxml'),'<view class="page"><view class="title">语音包已准备好</view><view class="body">返回课程，点击“听发音”即可使用。内置音频为西班牙西语合成音，不自动评价发音。</view><button class="primary" bindtap="back">返回课程</button></view>\n');
}
fs.writeFileSync(path.join(root,'miniprogram/data/audio-manifest.js'),'// Generated by scripts/package-audio.js; exact Spanish text → bundled MP3.\nmodule.exports = '+JSON.stringify(manifest,null,2)+';\n');
const appPath=path.join(root,'miniprogram/app.json'),app=JSON.parse(fs.readFileSync(appPath));
app.subPackages=[...packs].map(name=>({name,root:name,pages:['index']}));fs.writeFileSync(appPath,JSON.stringify(app,null,2)+'\n');
console.log(`${texts.length} audio clips, ${total} bytes, ${packs.size} native subpackages.`);
